/**
 * `pnpm report:rewind [dataDir] [outMd] [outJson]`: the Phase 5 counterfactual
 * (docs/REWIND.md + docs/rewind.json). Every number is produced by
 * rewind() in the engine; nothing here is typed by hand.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { DateTime } from 'luxon';
import { ET_ZONE, rewind, snapshotAsOfMs, type RewindReport } from '@lookahead/engine';
import { loadDataset } from '@lookahead/engine/loaders';
import { stableJson } from './lib/freeze';

const dataDir = process.argv[2] ?? 'data/raw';
const outMd = process.argv[3] ?? 'docs/REWIND.md';
const outJson = process.argv[4] ?? 'docs/rewind.json';
const dataset = loadDataset(dataDir);
const now = snapshotAsOfMs(dataset) ?? Math.max(...dataset.events.map((e) => e.ingestedAt));
const t0 = performance.now();
const r = rewind(dataset, now);
const ms = Math.round(performance.now() - t0);
const hm = (x: number | null) => (x === null ? '—' : DateTime.fromMillis(x, { zone: ET_ZONE }).toFormat('HH:mm'));

export function renderRewind(r: RewindReport): string {
  const lines = [
    '<!-- Generated by `pnpm report:rewind` (scripts/rewind-report.ts). Do not edit by hand. -->',
    '# Rewind: the day as if Lookahead had been running',
    '',
    `Origins every ${r.stepMin} min from ${hm(r.fromMs)} to ${hm(r.toMs)} ET on the reference package; at each origin the surge forecast, the standby plan and the activation trigger run on knowledge-time state only (events ingested by the origin). Unassigned stroke minutes are counted to ${hm(r.evalHorizonMs)} ET.`,
    '',
    '## Assumptions (LOOKAHEAD-DEFINED, illustrative)',
    '',
    `| lead approval | acknowledgment | activation approval | accept | time to come online |`,
    `| --- | --- | --- | --- | --- |`,
    `| ${r.assumptions.leadApprovalMin} min | ${r.assumptions.ackMin} min | ${r.assumptions.activationApprovalMin} min | ${r.assumptions.acceptMin} min | roster est_minutes_to_online |`,
    '',
    r.assumptions.note,
    '',
    '## Timeline',
    '',
    '| time (ET) | marker | hospital | physician | detail |',
    '| --- | --- | --- | --- | --- |',
    ...r.markers.map((m) => `| ${hm(m.tMs)} | ${m.kind} | ${m.hospitalId ?? ''} | ${m.physicianId ?? ''} | ${m.detail} |`),
    '',
    '## Three lines: stroke consult-minutes unassigned',
    '',
    '| line | online at | physician | total minutes |',
    '| --- | --- | --- | --- |',
    ...r.lines.map((l) => `| ${l.kind} | ${hm(l.onlineAtMs)} | ${l.physicianId ?? '—'} | ${l.totalStrokeMinutesUnassigned} |`),
    '',
    '### Consults whose outcome differs between the lines',
    '',
    '| consult | hospital | received | actual assigned | reactive assigned | anticipatory assigned | actual min | reactive min | anticipatory min |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  const [a, b, c] = r.lines;
  for (let i = 0; i < (a?.perConsult.length ?? 0); i++) {
    const x = a?.perConsult[i];
    const y = b?.perConsult[i];
    const z = c?.perConsult[i];
    if (!x || !y || !z) continue;
    if (x.minutesUnassigned === y.minutesUnassigned && x.minutesUnassigned === z.minutesUnassigned) continue;
    lines.push(`| ${x.consultId} | ${x.hospitalId} | ${hm(x.receivedMs)} | ${hm(x.assignedMs)} (${x.assignedTo ?? '—'}) | ${hm(y.assignedMs)} (${y.assignedTo ?? '—'}) | ${hm(z.assignedMs)} (${z.assignedTo ?? '—'}) | ${x.minutesUnassigned} | ${y.minutesUnassigned} | ${z.minutesUnassigned} |`);
  }
  lines.push('', '## Reading the result', '', ...r.explanation.map((e) => `- ${e}`), '');
  lines.push('## Per-origin recommendations', '', '| origin | rule tripped | deadlocks | P(gap) >= 0.5 | pre-alert recommended | activation |', '| --- | --- | --- | --- | --- | --- |');
  for (const o of r.origins) {
    const risky = Object.entries(o.pGapByHospital).filter(([, v]) => v >= 0.5).map(([h, v]) => `${h} ${v}`).join(', ');
    lines.push(`| ${hm(o.tMs)} | ${o.ruleTripped ? 'yes' : ''} | ${o.deadlocks.join(', ')} | ${risky} | ${o.recommendedPreAlert.join(', ')} | ${o.activationRecommended ? 'recommended' : ''} |`);
  }
  lines.push('', `Engaged-duration medians (minutes, from the stream): ${Object.entries(r.engagedMedianMin).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '');
  return lines.join('\n');
}

mkdirSync(dirname(outMd), { recursive: true });
writeFileSync(outMd, renderRewind(r));
writeFileSync(outJson, stableJson({ ...r, generatedFrom: dataDir }) + '\n');
console.log(`rewind: ${r.origins.length} origins in ${ms} ms; lines ${r.lines.map((l) => `${l.kind} ${l.totalStrokeMinutesUnassigned}`).join(', ')}`);
console.log(`wrote ${outMd} and ${outJson}`);
