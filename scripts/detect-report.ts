/**
 * `pnpm report:detect [dataDir] [HH:MM:SS] [outFile]` -> human-readable dump of
 * the DetectionReport (default: the snapshot instant, docs/DETECT_<label>.md).
 * For clinical-sense review; every number comes from detect().
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { DateTime } from 'luxon';
import { ET_ZONE, blockingExclusions, detect, etDateOf, etWallClockToEpoch, snapshotAsOfMs, type CoverageGap, type CoveragePoint } from '@lookahead/engine';
import { loadDataset } from '@lookahead/engine/loaders';

const dataDir = process.argv[2] ?? 'data/raw';
const dataset = loadDataset(dataDir);
const clockArg = process.argv[3];
const latest = dataset.events.reduce((m, e) => Math.max(m, e.eventTime), 0);
const nowMs = clockArg === undefined ? snapshotAsOfMs(dataset) : etWallClockToEpoch(etDateOf(latest), toSeconds(clockArg));
if (nowMs === null) throw new Error('no snapshot instant; pass HH:MM:SS');
const label = DateTime.fromMillis(nowMs, { zone: ET_ZONE }).toFormat('HHmm');
const outPath = process.argv[4] ?? `docs/DETECT_${label}.md`;

function toSeconds(hms: string): number {
  const [h = '0', m = '0', s = '0'] = hms.split(':');
  return Number(h) * 3600 + Number(m) * 60 + Number(s);
}
const t = (ms: number) => DateTime.fromMillis(ms, { zone: ET_ZONE }).toFormat('HH:mm:ss');
const hm = (ms: number) => DateTime.fromMillis(ms, { zone: ET_ZONE }).toFormat('HH:mm');
const min = (ms: number) => (ms / 60_000).toFixed(1).replace(/\.0$/, '');
const cell = (v: unknown) => String(v ?? '').replace(/\|/g, '\\|');
const out: string[] = [];
const p = (s = '') => out.push(s);
const table = (head: string[], rows: unknown[][]) => {
  p(`| ${head.join(' | ')} |`);
  p(`| ${head.map(() => '---').join(' | ')} |`);
  for (const r of rows) p(`| ${r.map(cell).join(' | ')} |`);
  p();
};

const r = detect(dataset, nowMs);
const names = r.staffing.hospitalNames;
const phys = (id: string) => `${r.staffing.physicianNames.get(id) ?? id} (${id})`;

p(`<!-- Generated by \`pnpm report:detect\` (scripts/detect-report.ts). Do not edit by hand. -->`);
p(`# Detection report at ${t(nowMs)} ET`);
p();
p(`Built from \`detect(dataset, ${nowMs})\` on \`${dataDir}\`: replay of events known at ${t(nowMs)} ET (correct mode), projection horizon ${r.horizonMin} min.`);
p(`Every rule cites the brief section and open question (docs/OPEN_QUESTIONS.md) it encodes. No patient information is used beyond consult ids, consult type and stage.`);
p();
p(`**Summary:** ${r.attention.length} attention items (${['critical', 'high', 'medium', 'low'].map((s) => `${r.attention.filter((a) => a.severity === s).length} ${s}`).join(', ')}); ` +
  `${r.standards.filter((s) => s.level !== 'ok').length} standards breached; ${r.deadlocks.length} routing deadlocks; ` +
  `${r.demand.filter((d) => d.spike).length} demand spike(s); ${r.coverage.gaps.length} projected coverage gap(s) (${r.coverage.gapsExcludingArrivals.length} if scheduled arrivals are ignored).`);
p();

p('## 1. Attention list (ranked)');
p();
r.attention.forEach((a, i) => {
  p(`### ${i + 1}. [${a.severity.toUpperCase()} · ${a.score}] ${a.headline}`);
  p();
  p(`Kind \`${a.kind}\` · stroke at risk: ${a.strokeAtRisk ? 'yes' : 'no'} · impact ${a.timeToImpactMs === 0 ? 'now' : `in ${min(a.timeToImpactMs)} min`} · id \`${a.id}\``);
  p();
  for (const w of a.why) p(`- ${w}`);
  p(`- Score: ${a.scoreBreakdown.map((f) => `${f.factor} ${f.points}`).join(' + ')} = ${a.score}`);
  p(`- Evidence: ${a.because.map((b) => `${b.eventId} (${b.eventType} ${t(b.eventTimeMs)})`).join(', ')}`);
  p();
});

p('## 2. Time standards (brief "Operational Standards")');
p();
table(
  ['consult', 'type', 'hospital', 'standard', 'level', 'clock start', 'elapsed (min)', 'warning at', 'critical at'],
  r.standards.map((s) => [s.consultId, s.consultType, names.get(s.hospitalId ?? '') ?? s.hospitalId, s.label, s.level, t(s.clockStartMs), min(s.elapsedMs), t(s.warnAtMs), t(s.criticalAtMs)]),
);

p('## 3. Open notes near shift end (OQ-22)');
p();
table(
  ['physician', 'shift ends', 'window opens', 'in window', 'open notes', 'level now', 'level when window opens'],
  r.openNotes.map((n) => [phys(n.physicianId), hm(n.shiftEndMs), hm(n.windowEntersAtMs), n.inWindow ? 'yes' : 'no', n.noteConsultIds.join(', ') || '-', n.level, n.levelAtWindow]),
);

p('## 4. Demand (trailing 60 min vs p90 for the ET hour; OQ-03, OQ-19)');
p();
table(
  ['hospital', 'received (now-60m, now]', 'p90', 'mean', 'ratio to mean', 'spike', 'consults'],
  r.demand.map((d) => [`${d.hospitalName} (${d.hospitalId})`, d.count, d.p90, d.mean, d.ratioToMean === null ? '-' : d.ratioToMean.toFixed(1), d.spike ? '**yes**' : 'no', d.contributingConsultIds.join(', ') || '-']),
);

p('## 5. Coverage projection (staffed capacity, OQ-24(a))');
p();
const gapRows = (gaps: readonly CoverageGap[]) =>
  gaps.map((g) => [`${g.hospitalName} (${g.hospitalId})`, hm(g.startMs), g.endMs === 'beyond_horizon' ? 'beyond horizon' : hm(g.endMs), `${g.staffed}/${g.required}`, g.whoRemains.join(', ') || 'nobody', g.causes.map((c) => c.detail).join('; ')]);
p('**Gaps, default (scheduled arrivals from the off-shift roster count from their start, OQ-27):**');
p();
table(['hospital', 'from', 'until', 'staffed/required', 'still counted', 'causes'], gapRows(r.coverage.gaps));
p('**Gaps if scheduled arrivals are ignored:**');
p();
table(['hospital', 'from', 'until', 'staffed/required', 'still counted', 'causes'], gapRows(r.coverage.gapsExcludingArrivals));
const boundaries = [...new Set([r.coverage.timeline[0]?.tMs, ...r.coverage.timeline.map((x) => x.tMs).filter((x) => DateTime.fromMillis(x, { zone: ET_ZONE }).minute === 0)])].filter((x): x is number => x !== undefined);
const pick = (tl: readonly CoveragePoint[], ms: number, h: string) => tl.find((x) => x.tMs === ms)?.perHospital[h];
p('**Staffed / required at each hour mark (with arrivals · without arrivals):**');
p();
table(
  ['hospital', ...boundaries.map(hm)],
  dataset.hospitals.map((h) => [
    `${h.hospitalName} (${h.hospitalId})`,
    ...boundaries.map((b) => {
      const a = pick(r.coverage.timeline, b, h.hospitalId);
      const x = pick(r.coverage.timelineExcludingArrivals, b, h.hospitalId);
      const flag = (v: typeof a) => (v !== undefined && v.staffed < v.required ? '**' : '');
      return `${flag(a)}${a?.staffed}/${a?.required}${flag(a)} · ${flag(x)}${x?.staffed}/${x?.required}${flag(x)}`;
    }),
  ]),
);

p('## 6. Routable now (routing rules 1-2, OQ-24(b))');
p();
table(
  ['hospital', 'routable now', 'routing would pick', 'blocked (on shift and credentialed)'],
  dataset.hospitals.map((h) => {
    const choice = r.routes[h.hospitalId];
    return [
      `${h.hospitalName} (${h.hospitalId})`,
      r.coverage.routableNow[h.hospitalId] ?? 0,
      choice?.chosen ? `${phys(choice.chosen)}: ${choice.ranked[0]?.why}` : 'nobody (rule 5)',
      choice ? blockingExclusions(choice).map((x) => `${x.physicianId}: ${x.failedRules.map((f) => f.detail).join('; ')}`).join('<br>') : '',
    ];
  }),
);

p('## 7. Routing deadlocks');
p();
for (const d of r.deadlocks) {
  p(`- **${d.consultId}** (${d.consultType}, ${d.stage}) at ${names.get(d.hospitalId)}: ${d.routingFailures.length} routing failure(s); ${blockingExclusions(d.choice).map((x) => `${phys(x.physicianId)}: ${x.failedRules.map((f) => f.detail).join('; ')}`).join(' / ')}`);
}
if (r.deadlocks.length === 0) p('- none');
p();

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${out.join('\n').trimEnd()}\n`);
console.log(`report:detect: wrote ${outPath} (${r.attention.length} attention items)`);
