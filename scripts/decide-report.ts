/**
 * `pnpm report:decide [dataDir] [HH:MM:SS] [outFile]` -> human-readable dump of
 * the DecisionReport (default: the snapshot instant, docs/DECIDE_<label>.md).
 * For clinical-sense review; every number comes from decide().
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { DateTime } from 'luxon';
import { ET_ZONE, decide, etDateOf, etWallClockToEpoch, snapshotAsOfMs, type Need, type PrioritySnapshotRow } from '@lookahead/engine';
import { loadDataset } from '@lookahead/engine/loaders';

const dataDir = process.argv[2] ?? 'data/raw';
const dataset = loadDataset(dataDir);
const clockArg = process.argv[3];
const latest = dataset.events.reduce((m, e) => Math.max(m, e.eventTime), 0);
const nowMs = clockArg === undefined ? snapshotAsOfMs(dataset) : etWallClockToEpoch(etDateOf(latest), toSeconds(clockArg));
if (nowMs === null) throw new Error('no snapshot instant; pass HH:MM:SS');
const label = DateTime.fromMillis(nowMs, { zone: ET_ZONE }).toFormat('HHmm');
const outPath = process.argv[4] ?? `docs/DECIDE_${label}.md`;

function toSeconds(hms: string): number {
  const [h = '0', m = '0', s = '0'] = hms.split(':');
  return Number(h) * 3600 + Number(m) * 60 + Number(s);
}
const t = (ms: number) => DateTime.fromMillis(ms, { zone: ET_ZONE }).toFormat('HH:mm:ss');
const hm = (ms: number) => DateTime.fromMillis(ms, { zone: ET_ZONE }).toFormat('HH:mm');
const endOf = (n: Need) => (n.endMs === 'beyond_horizon' ? 'beyond projection' : hm(n.endMs));
const cell = (v: unknown) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, '<br>');
const out: string[] = [];
const p = (s = '') => out.push(s);
const table = (head: string[], rows: unknown[][]) => {
  p(`| ${head.join(' | ')} |`);
  p(`| ${head.map(() => '---').join(' | ')} |`);
  for (const r of rows) p(`| ${r.map(cell).join(' | ')} |`);
  p();
};

const r = decide(dataset, nowMs);
const names = r.detection.staffing.hospitalNames;
const hosp = (id: string) => `${names.get(id) ?? id} (${id})`;
const needKind = new Map(r.whatIf.before.map((n) => [n.id, n]));

p(`<!-- Generated by \`pnpm report:decide\` (scripts/decide-report.ts). Do not edit by hand. -->`);
p(`# Decision report at ${t(nowMs)} ET`);
p();
p(`Built from \`decide(dataset, ${nowMs})\` on \`${dataDir}\`. Detection horizon ${r.detection.horizonMin} min; decision projection ${Math.round((r.decisionCoverage.horizonEndMs - nowMs) / 60_000)} min (OQ-31).`);
p(`Decide is deterministic rules only; no LLM is in this path. Every rule cites the brief section and open question (docs/OPEN_QUESTIONS.md) it encodes.`);
p();
p(`**Summary:** ${r.needs.length} needs (${['DEADLOCK_NOW', 'HARD_GAP', 'AT_RISK'].map((k) => `${r.needs.filter((n) => n.kind === k).length} ${k}`).join(', ')}); ` +
  `${r.ledger.filter((e) => e.eligible).length} of ${r.ledger.length} off-shift physicians eligible; ` +
  `recommended offer: ${r.recommendedOffer === null ? 'none' : `${r.recommendedOffer.name} (${r.recommendedOffer.physicianId}) ${hm(r.recommendedOffer.window.startMs)}-${hm(r.recommendedOffer.window.endMs)} ET`}; ${r.interventions.length} interventions.`);
p();

p('## 1. Needs (start within the detection horizon)');
p();
table(
  ['kind', 'hospital', 'from', 'until', 'severity', 'required', 'confirmed + expected', 'qualifies for offers (OQ-30)', 'consults', 'why'],
  r.needs.map((n) => [n.kind, hosp(n.hospitalId), hm(n.startMs), endOf(n), n.severity, n.required ?? '-', n.required === null ? '-' : `${n.staffedConfirmed} + ${n.staffedExpected}`, n.qualifiesForOffers ? 'yes' : 'no (advisory)', n.consultIds.join(', ') || '-', n.why.join('\n')]),
);
p('**Gap hospitals:**');
p();
table(['hospital', 'need kinds', 'qualifies for offers'], r.gapHospitals.map((g) => [hosp(g.hospitalId), g.kinds.join(', '), g.qualifiesForOffers ? 'yes' : 'no']));

p('## 2. Split-shift eligibility ledger (brief "Coverage and Split-Shift Eligibility")');
p();
for (const e of r.ledger) {
  p(`### ${e.name} (${e.physicianId}): ${e.eligible ? `**ELIGIBLE**, rank ${e.rank}` : 'not eligible'}`);
  p();
  table(['rule', 'result', 'detail'], e.rules.map((x) => [x.rule, x.pass === null ? 'n/a' : x.pass ? 'pass' : '**FAIL**', x.detail]));
  if (e.offerWindow !== null) {
    const w = e.offerWindow;
    p(`Window: sent ${hm(w.sentMs)}, start ${hm(w.startMs)} (+${w.minutesToOnline} min to online), end ${hm(w.endMs)}; offered ${w.offeredMinutes} min, effective ${w.effectiveMinutes} min; binding cap \`${w.bindingCap}\`.`);
    p(`Caps: ${w.caps.map((c) => `${c.kind} ${DateTime.fromMillis(c.atMs, { zone: ET_ZONE }).toFormat('MM-dd HH:mm')} (${c.detail})`).join('; ')}.`);
    p();
    p(`Value ${e.value}: ${e.valueTerms.map((v) => `${v.kind} ${v.hospitalId} ${v.minutes} min x ${v.weight}`).join(' + ') || 'none'}.`);
    p();
  }
}

const o = r.recommendedOffer;
p('## 3. Recommended offer');
p();
if (o === null) p('No eligible physician: no split-shift offer can be recommended.');
else {
  table(
    ['physician', 'window', 'routing scope', 'seeded consults', 'value', 'covers needs'],
    [[`${o.name} (${o.physicianId})`, `${hm(o.window.startMs)}-${hm(o.window.endMs)} ET`, o.routingScope.map(hosp).join(', '), o.seededConsultCount, o.value, o.coversNeeds.map((id) => { const n = needKind.get(id) ?? r.needs.find((x) => x.id === id); return n ? `${n.kind} ${n.hospitalId} ${hm(n.startMs)}` : id; }).join('; ')]],
  );
  for (const w of o.why) p(`- ${w}`);
  p();
  p('**Message (PHI-checked: denylist + whitelist):**');
  p();
  p('```');
  p(o.message);
  p('```');
  p();
}

p('## 4. Split-shift trap (OQ-35)');
p();
const trapTable = (rows: readonly PrioritySnapshotRow[]) =>
  table(['hospital', 'in scope', 'joiner consults', 'tier', 'first pick', 'why'], rows.map((x) => [hosp(x.hospitalId), x.inScope ? 'yes' : 'no', x.joinerConsults, x.joinerTier, x.firstPick ? '**yes**' : 'no', x.why]));
if (o !== null) {
  p(`**${o.physicianId} at ${hm(o.trap.startMs)} ET, before mitigation:**`);
  p();
  trapTable(o.trap.before);
  p(`**After ${o.trap.recommended.toUpperCase().replace(/_/g, ' ')}:**`);
  p();
  trapTable(o.trap.after);
  for (const w of o.trap.trapWhy) p(`- ${w}`);
  p();
}
for (const a of r.arrivalTraps) {
  p(`**Scheduled arrival ${a.physicianId} at ${hm(a.startMs)} ET (advisory):**`);
  p();
  for (const w of a.trapWhy) p(`- ${w}`);
  p();
}

p('## 5. Top-issue recommendation');
p();
if (r.recommendation !== null) {
  p(`**${r.recommendation.headline}**`);
  p();
  r.recommendation.actions.forEach((a, i) => p(`${i + 1}. \`${a.kind}\` (proposer ${a.proposer}${a.approver ? `, approver ${a.approver}` : ''}${a.acceptor ? `, acceptor ${a.acceptor}` : ''}): ${a.expectedEffect}`));
  p();
  for (const w of r.recommendation.rationale) p(`- ${w}`);
  p();
}

p('## 6. Interventions');
p();
table(
  ['kind', 'consults', 'physicians', 'hospitals', 'proposer -> approver -> acceptor', 'automation', 'expected effect', 'why'],
  r.interventions.map((i) => [i.kind, i.targets.consultIds.join(', ') || '-', i.targets.physicianIds.join(', ') || '-', i.targets.hospitalIds.join(', ') || '-', [i.proposer, i.approver ?? '-', i.acceptor ?? '-'].join(' -> '), i.automationAllowed ? 'yes (internal alert)' : 'no', i.expectedEffect, i.why.join('\n')]),
);

p('## 7. What-if: accept the recommended offer (decision projection, OQ-31)');
p();
if (r.whatIf.after !== null) {
  p(`Routable at offer start: ${r.whatIf.after.routableAtOfferStart.map((x) => `${x.hospitalId} ${x.count} (${x.ids.join(', ')})`).join('; ')}.`);
  p();
  table(
    ['before', 'hospital', 'from', 'until', 'outcome', 'after'],
    r.whatIf.changes.map((c) => [c.before.kind, hosp(c.before.hospitalId), hm(c.before.startMs), endOf(c.before), c.outcome, c.detail]),
  );
  if (r.whatIf.introduced.length > 0) {
    p('**Introduced by the offer:**');
    p();
    table(['kind', 'hospital', 'from', 'until'], r.whatIf.introduced.map((n) => [n.kind, hosp(n.hospitalId), hm(n.startMs), endOf(n)]));
  }
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${out.join('\n')}\n`);
console.log(`wrote ${outPath} (${r.needs.length} needs, ${r.ledger.length} ledger entries, ${r.interventions.length} interventions)`);
