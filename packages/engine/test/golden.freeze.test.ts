import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { freezeDecision, freezeLog, subsetDiffs } from '../../../scripts/lib/freeze';
import { applyCommand, decide, type ActionLog } from '../src';
import { ctx, dataset, must } from './act.helpers';

const COORD = { role: 'coordinator', id: 'coordinator-on-duty' } as const;
const LEAD = { role: 'clinical_lead', id: 'clinical-lead-on-duty' } as const;
import { et } from './helpers';

/**
 * Phase 0 golden freeze (non-negotiable 1: "Additive only. New layers never
 * change brief-defined outputs"). test/golden/freeze_1820.json holds
 * detect()+decide() at 18:20 and the action log after the demo loop's happy
 * path, generated by `pnpm golden:freeze` before the final build started.
 * Every frozen field must stay deep-equal; new fields are allowed.
 */
const golden = JSON.parse(readFileSync(fileURLToPath(new URL('./golden/freeze_1820.json', import.meta.url)), 'utf8')) as { decide1820: unknown; demoLoop: { log: unknown } };

describe('golden freeze: pre-existing outputs stay deep-equal (subset) for the rest of the build', () => {
  it('detect() + decide() at 18:20', () => {
    const diffs = subsetDiffs(freezeDecision(decide(dataset, et('18:20:00'))), golden.decide1820);
    expect(diffs.slice(0, 20), `${diffs.length} frozen field(s) changed`).toEqual([]);
  });

  it('action log after the demo loop (propose 18:21, approve 18:22, accept 18:24)', () => {
    const top = decide(dataset, et('18:20:00')).recommendedOffer?.physicianId ?? '';
    let log: ActionLog = must(ctx, [], { type: 'proposeOffer', commandId: 'demo-propose', actor: COORD, physicianId: top }, '18:21:00');
    const offerId = log[0]?.type === 'offer_proposed' ? log[0].payload.offerId : '';
    log = must(ctx, log, { type: 'approveOffer', commandId: 'demo-approve', actor: LEAD, offerId }, '18:22:00');
    const r = applyCommand(ctx, log, { type: 'respond', commandId: 'demo-accept', actor: { role: 'physician', id: top }, offerId, physicianId: top, response: 'accept' }, et('18:24:00'));
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    const diffs = subsetDiffs(freezeLog(r.log), golden.demoLoop.log);
    expect(diffs.slice(0, 20), `${diffs.length} frozen field(s) changed`).toEqual([]);
  });
});
