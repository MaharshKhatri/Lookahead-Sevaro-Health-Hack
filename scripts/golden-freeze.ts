/**
 * `pnpm golden:freeze`: writes the Phase 0 golden freeze fixtures. Pre-existing
 * engine outputs (detect + decide at 18:20, and the action log after the demo
 * loop's happy path) are frozen as JSON; `test/golden.freeze.test.ts` checks
 * that every frozen field is still deep-equal. New layers may only ADD fields
 * (non-negotiable 1: additive only), so the check is a subset comparison.
 *
 * The web view fixture is written by `apps/web/test/golden.freeze.test.ts`
 * when GOLDEN_FREEZE_WRITE=1 (it needs the route harness).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { applyCommand, decide, etDateOf, etWallClockToEpoch, snapshotAsOfMs, type ActContext, type ActionLog } from '@lookahead/engine';
import { loadDataset } from '@lookahead/engine/loaders';
import { freezeDecision, freezeLog, stableJson } from './lib/freeze';

const dataDir = process.argv[2] ?? 'data/raw';
const outPath = process.argv[3] ?? 'packages/engine/test/golden/freeze_1820.json';
const dataset = loadDataset(dataDir);
const snapshot = snapshotAsOfMs(dataset);
if (snapshot === null) throw new Error('no snapshot instant');
const day = etDateOf(snapshot);
const at = (hms: string) => {
  const [h = '0', m = '0', s = '0'] = hms.split(':');
  return etWallClockToEpoch(day, Number(h) * 3600 + Number(m) * 60 + Number(s));
};

const d0 = decide(dataset, at('18:20:00'));
const ctx: ActContext = { dataset };
const COORD = { role: 'coordinator', id: 'coordinator-on-duty' } as const;
const LEAD = { role: 'clinical_lead', id: 'clinical-lead-on-duty' } as const;
const top = d0.recommendedOffer?.physicianId ?? '';
let log: ActionLog = [];
const step = (c: Parameters<typeof applyCommand>[2], hms: string) => {
  const r = applyCommand(ctx, log, c, at(hms));
  if (!r.ok) throw new Error(`${c.type} failed: ${r.code} ${r.message}`);
  log = r.log;
};
step({ type: 'proposeOffer', commandId: 'demo-propose', actor: COORD, physicianId: top }, '18:21:00');
const offerId = log.find((e) => e.type === 'offer_proposed')?.type === 'offer_proposed' ? (log[0] as { payload: { offerId: string } }).payload.offerId : '';
step({ type: 'approveOffer', commandId: 'demo-approve', actor: LEAD, offerId }, '18:22:00');
step({ type: 'respond', commandId: 'demo-accept', actor: { role: 'physician', id: top }, offerId, physicianId: top, response: 'accept' }, '18:24:00');

const fixture = {
  note: 'Golden freeze (Phase 0). Generated by `pnpm golden:freeze`; do not edit by hand. Subset-compared by test/golden.freeze.test.ts.',
  decide1820: freezeDecision(d0),
  demoLoop: { log: freezeLog(log) },
};
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, stableJson(fixture) + '\n');
console.log(`wrote ${outPath}`);
